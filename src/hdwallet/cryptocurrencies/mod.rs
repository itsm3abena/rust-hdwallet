use crate::hdwallet::exceptions::{Error, Result};

pub struct Cryptocurrencies;

impl Cryptocurrencies {
    pub fn classes() -> &'static [&'static icryptocurrency::CryptocurrencyDescriptor] {
        DESCRIPTORS
    }
}

pub fn get_cryptocurrency(symbol: &str) -> Result<&'static icryptocurrency::CryptocurrencyDescriptor> {
    for descriptor in Cryptocurrencies::classes() {
        if descriptor.symbol == symbol {
            return Ok(descriptor);
        }
    }
    Err(Error::new(
        &format!("Cryptocurrency not found with this {symbol} symbol"),
        None,
        None,
        Some(symbol),
    ))
}

pub fn resolve_network<'a>(
    descriptor: &'a icryptocurrency::CryptocurrencyDescriptor,
    network: &str,
) -> Result<&'a icryptocurrency::NetworkDescriptor> {
    descriptor
        .networks
        .iter()
        .find_map(|(_, item)| {
            if item.name.eq_ignore_ascii_case(network) {
                Some(*item)
            } else {
                None
            }
        })
        .ok_or_else(|| {
            let expected = descriptor
                .networks
                .iter()
                .map(|(_, item)| item.name)
                .collect::<Vec<_>>()
                .join(", ");
            Error::new(
                &format!("Invalid {} cryptocurrency network", descriptor.name),
                None,
                Some(&expected),
                Some(network),
            )
        })
}

